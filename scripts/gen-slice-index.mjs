// Writes the slice index that apps/api and apps/worker import. Adding a slice
// is adding slices/<name>/register.ts; nothing else is edited, because the
// index is generated and git-ignored. apps/web uses a Vite glob instead.
import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APPS = ["api", "worker"];

const sliceNames = async (root) => {
  const entries = await readdir(join(root, "slices"), { withFileTypes: true }).catch(() => []);
  const registered = await Promise.all(
    entries
      .filter((e) => e.isDirectory())
      .map(async (e) => ((await stat(join(root, "slices", e.name, "register.ts")).catch(() => null)) ? e.name : null)),
  );
  return registered.filter(Boolean).sort();
};

const render = (names) =>
  [
    "// Generated by scripts/gen-slice-index.mjs. Do not edit.",
    'import type { Slice } from "@mojibun/slice";',
    ...names.map((n, i) => `import slice${i} from "../../../slices/${n}/register.ts";`),
    `export const slices: Slice[] = [${names.map((_, i) => `slice${i}`).join(", ")}];`,
    "",
  ].join("\n");

export const generate = async (root) => {
  const names = await sliceNames(root);
  const written = [];
  for (const app of APPS) {
    const file = join(root, "apps", app, "src", "slices.generated.ts");
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, render(names));
    written.push(file);
  }
  return written;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), ".."));
  await generate(root);
}
